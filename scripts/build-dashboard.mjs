// Builds the dashboard served at "/": source/template.html + source/program.json + dashboard/rest-shim.js
// -> src/generated/dashboard.js (git-ignored; runs automatically before `wrangler deploy` / `wrangler dev`).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { buildHtml } = createRequire(import.meta.url)(path.join(root, "source/build.js"));

const shim = fs.readFileSync(path.join(root, "dashboard/rest-shim.js"), "utf8");
// template.html is a page fragment (claude.ai artifacts add the document skeleton and the [hidden] rule).
// Served by the Worker it needs both, or the browser runs in quirks mode and shows every tab at once.
const head = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex"><style>[hidden]{display:none !important}</style>`;
const page = buildHtml({ shim });
const html = /^\s*<!doctype/i.test(page) ? page : `${head}\n${page}\n</html>\n`;
const out = path.join(root, "src/generated/dashboard.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by scripts/build-dashboard.mjs - do not edit.\nexport const DASHBOARD_HTML = ${JSON.stringify(html)};\n`);
console.log(`dashboard built: ${html.length} bytes -> ${path.relative(root, out)}`);
